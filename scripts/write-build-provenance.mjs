/**
 * Record the commit that this bundle is built from.
 * Do not hand-edit lib/build.generated.mjs. A committed SHA goes stale.
 *
 * Order: git rev-parse HEAD, then Workers Builds WORKERS_CI_COMMIT_SHA,
 * then CF_PAGES_COMMIT_SHA, then a 40-hex SOURCE_BASE_TIP in the build
 * environment. Runtime wrangler vars are a separate override and are not
 * written here.
 */
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "lib", "build.generated.mjs");
const SHA40 = /^[0-9a-f]{40}$/;

function readSha(name) {
  const value = String(process.env[name] || "").trim().toLowerCase();
  return SHA40.test(value) ? value : "";
}

function gitHead() {
  try {
    const value = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"]
    })
      .trim()
      .toLowerCase();
    return SHA40.test(value) ? value : "";
  } catch {
    return "";
  }
}

const git = gitHead();
const workersCi = readSha("WORKERS_CI_COMMIT_SHA");
const pages = readSha("CF_PAGES_COMMIT_SHA");
const fromBuildEnv = readSha("SOURCE_BASE_TIP");

let source = "";
let captured = "";
if (git) {
  source = git;
  captured = "git-rev-parse-HEAD";
} else if (workersCi) {
  source = workersCi;
  captured = "WORKERS_CI_COMMIT_SHA";
} else if (pages) {
  source = pages;
  captured = "CF_PAGES_COMMIT_SHA";
} else if (fromBuildEnv) {
  source = fromBuildEnv;
  captured = "SOURCE_BASE_TIP";
}

if (!source) {
  console.error(
    "write-build-provenance: no git HEAD, WORKERS_CI_COMMIT_SHA, CF_PAGES_COMMIT_SHA, or 40-hex SOURCE_BASE_TIP."
  );
  process.exit(1);
}

const body = `// Generated by scripts/write-build-provenance.mjs. Do not hand-edit.
// Gitignored. npm test and wrangler deploy regenerate this file.
export const GENERATED_BUILD = {
  source_base_tip: ${JSON.stringify(source)},
  captured: ${JSON.stringify(captured)}
};
`;

let previous = "";
try {
  previous = await readFile(outFile, "utf8");
} catch {
  previous = "";
}
if (previous !== body) await writeFile(outFile, body);
console.log(`provenance ${source} via ${captured}`);
